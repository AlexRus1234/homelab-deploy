#!/bin/bash
# Общие проверки для харнессов контура.
#
# Подключается харнессами (`. "$HERE/harness-lib.sh"`). Смысл: без решения «зелено/красно» прогон
# бесполезен — и pre-push хук, и CI смотрят только на код возврата, а не на глаза человека.
# Харнесс печатает подробности по секциям (что он делал), а вердикт выносят вот эти функции:
# каждая строка — `ok` или `FAIL` с ожиданием и фактом, провалы считаются, в конце харнесс
# возвращает ненулевой код, если был хотя бы один провал.
#
# Не харнесс сам по себе: ничего не запускает, только сравнивает.

CHECKS=0
FAILS=0

check() { # описание, ожидание, факт
    CHECKS=$((CHECKS + 1))
    if [ "$2" = "$3" ]; then
        printf '  ok    %s\n' "$1"
    else
        printf '  FAIL  %s\n        ждали:    [%s]\n        получили: [%s]\n' "$1" "$2" "$3"
        FAILS=$((FAILS + 1))
    fi
}

has() { # описание, искомая строка, файл — подстрока, без регулярных выражений
    CHECKS=$((CHECKS + 1))
    if grep -qF -- "$2" "$3" 2>/dev/null; then
        printf '  ok    %s\n' "$1"
    else
        printf '  FAIL  %s: в %s нет строки [%s]\n' "$1" "$3" "$2"
        FAILS=$((FAILS + 1))
    fi
}

nothas() { # описание, нежеланная строка, файл
    CHECKS=$((CHECKS + 1))
    if grep -qF -- "$2" "$3" 2>/dev/null; then
        printf '  FAIL  %s: в %s есть строка [%s], которой быть не должно\n' "$1" "$3" "$2"
        FAILS=$((FAILS + 1))
    else
        printf '  ok    %s\n' "$1"
    fi
}

differs() { # описание, значение A, значение B — значения обязаны различаться
    CHECKS=$((CHECKS + 1))
    if [ "$2" != "$3" ]; then
        printf '  ok    %s\n' "$1"
    else
        printf '  FAIL  %s: оба значения [%s], а должны различаться\n' "$1" "$2"
        FAILS=$((FAILS + 1))
    fi
}

count() { # описание, ожидаемое число, файл, подстрока (считает вхождения)
    local got
    got=$(grep -cF -- "$4" "$3" 2>/dev/null || true)
    check "$1" "$2" "$got"
}

status_line() { # имя, действие, файл отчёта — печатает последнюю подходящую строку целиком
    awk -F'\t' -v n="$1" -v a="$2" '$1 == n && $2 == a { line = $0 } END { print line }' "$3"
}

status_field() { # имя, действие, номер поля, файл отчёта
    awk -F'\t' -v n="$1" -v a="$2" -v f="$3" '$1 == n && $2 == a { line = $f } END { print line }' "$4"
}

trace() { # шаблон grep -E, файл журнала — последовательность совпавших вызовов, разделитель |
    grep -oE "$1" "$2" 2>/dev/null | tr '\n' '|'
}

# Метки времени контура — только ОТНОСИТЕЛЬНО «сейчас». Жёсткая дата в фикстуре зеленеет в день
# написания и краснеет через сутки (окно удержания 24h): падает при этом не контур, а харнесс, и
# блокирует любой пуш, включая чужие правки (16.10 «свежая» стоянка фикстуры стала 41,7-часовой,
# контур снёс её правильно, а пять проверок легли). Хук pre-push дополнительно падает, если в
# tests/ появится абсолютная дата.
stamp_ago() { # «YYYYmmdd-HHMMSS» на N секунд назад; без аргумента — сейчас (GNU date, запасной BSD)
    local s=$(( $(date +%s) - ${1:-0} ))
    date -d "@$s" +%Y%m%d-%H%M%S 2>/dev/null || date -r "$s" +%Y%m%d-%H%M%S
}

stamp_epoch() { # «YYYYmmdd-HHMMSS» → epoch; нужно, чтобы проверять саму посылку фикстуры
    local d=${1//-/}
    date -d "${d:0:4}-${d:4:2}-${d:6:2} ${d:8:2}:${d:10:2}:${d:12:2}" +%s 2>/dev/null && return 0
    date -j -f "%Y%m%d%H%M%S" "$d" +%s 2>/dev/null
}

stamp_age() { # «YYYYmmdd-HHMMSS» → возраст в секундах
    local e
    e=$(stamp_epoch "$1") || return 1
    echo $(( $(date +%s) - e ))
}

summary() { # печатает итог и возвращает код (вызывать последней строкой харнесса)
    printf '\n=== %s: проверок %s, провалов %s\n' "$(basename "$0")" "$CHECKS" "$FAILS"
    [ "$FAILS" = 0 ] || return 1
    return 0
}
